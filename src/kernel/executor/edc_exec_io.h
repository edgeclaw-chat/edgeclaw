/* ─────────────────────────────────────────────────────────────────────────
 * executor's I/O vocabulary
 *
 * All the types the executor needs to interpret "what the LLM returned / what a
 * tool returned / what a tool will send". They used to live in llm_actor.h /
 * toolbox.h / toolbox_actor.h -- upper-layer headers (actors / toolbox) -- while
 * the executor is the lowest interpreter, so executor -> upper layer was a reverse
 * edge (invisible in a single-package build, a cycle once split by concept).
 *
 * Moving the definitions here and having the upper headers include this removes
 * the cycle. Pure definition move, zero behaviour change.
 * ───────────────────────────────────────────────────────────────────────── */
#ifndef __EDC_EXEC_IO_H__
#define __EDC_EXEC_IO_H__

#include "edc_config.h" /* edc_channel_type · edc_render_pref_t */
#include "edc_error.h"  /* EdcError */
#include "sds.h"
#include "utarray.h"
#include <stdint.h>
#include <cJSON.h>

struct edc_task; /* fwd: appears only as a pointer in edc_toolbox_actor_req */

/* ══ LLM response vocabulary ══════════════════════════════════════════════ */

typedef enum
{
    BC_LLM_FINISH_REASON_STOP,
    BC_LLM_FINISH_REASON_TOOL_CALL,
    BC_LLM_FINISH_REASON_LENGTH,
    BC_LLM_FINISH_REASON_SENSITIVE,
    BC_LLM_FINISH_REASON_NETWORK_ERROR,
    BC_LLM_FINISH_REASON_CONTEXT_EXCEEDED,
    BC_LLM_FINISH_REASON_UNKNOWN,
} edc_llm_actor_finish_reason_t;

typedef enum
{
    BC_LLM_CHAT_ROLE_USER,
    BC_LLM_CHAT_ROLE_ASSISTANT,
    BC_LLM_CHAT_ROLE_SYSTEM,
} edc_llm_actor_role_t;

typedef enum
{
    BC_LLM_TOOL_CALL_TYPE_FUNCTION,
} edc_llm_actor_tool_call_type_t;

struct edc_llm_chat_tool_call
{
    sds id;
    edc_llm_actor_tool_call_type_t type;
    size_t index;
    struct
    {
        sds name;
        cJSON *arguments;
    } function;
};

/* Token accounting reported by the provider for one chat completion: the
 * OpenAI/DeepSeek-compatible `usage` object. Every field is 0 when the
 * provider omits usage (some error paths, or a proxy that strips it), so
 * consumers can accumulate unconditionally without null checks. Counts are
 * per-response (one API call), not per-turn or per-session. */
struct edc_llm_usage
{
    int64_t prompt_tokens;     /* tokens in the request messages */
    int64_t completion_tokens; /* tokens generated by the model */
    int64_t total_tokens;      /* prompt + completion (0 if absent) */
    int64_t cached_tokens;     /* prompt tokens served from the provider's
                                    prompt cache: `prompt_tokens_details.
                                    cached_tokens` or the DeepSeek-specific
                                    `prompt_cache_hit_tokens` */
};

struct edc_llm_actor_resp
{
    edc_llm_actor_finish_reason_t reason;
    size_t index;
    sds content;
    sds reasoning_content;
    edc_llm_actor_role_t role;

    UT_array *tool_calls;
    cJSON *msg;
    EdcError *error;

    /* HTTP status of the response (0 = none: transport failure / no status line).
     * A provider-side error arrives here as HTTP 400 with the reason in the body,
     * a rate limit as 429 — the error text alone cannot always tell them apart. */
    int http_status;

    struct edc_llm_usage usage; /* zeroed when the provider omits `usage` */
};

/* ══ Tool-side vocabulary ═════════════════════════════════════════════════ */

struct edc_toolbox_actor_req
{
    sds name;
    cJSON *args;
    sds call_id;
    edc_channel_type call_from_type;
    struct edc_task *task; /* the task that issued this tool call (injected by app; NULL = non-task path) */
    sds result;
    struct edc_toolbox_actor_req *next;
};

/* A tool result goes to the scheduler actor first: the scheduler runs the
 * active-task gate on its own thread, and only then does app forward it as a TOOL
 * channel message. This struct is the toolbox -> scheduler payload. */
struct edc_toolbox_emit_msg
{
    sds header;
    sds content;
    edc_render_pref_t render_pref; /* render preference declared by the sender (default/PLAIN = plain text) */
};

#endif /* __EDC_EXEC_IO_H__ */
