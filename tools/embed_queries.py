#!/usr/bin/env python3
"""Embed a set of tree-sitter highlight queries as C byte arrays.

Build-time helper for //src/common:syntax. Turns one or more highlights.scm
files into a single C source + header so the queries are compiled into the
binary (no runtime file access, no network). Symbol names are derived from the
input file's basename: queries/c.scm -> edc_query_c and edc_query_c_size.

The escaping mirrors tools/embed_blob.py: an scm is ASCII in practice, but any
byte is representable and every escape is fixed-width where needed.
"""

import argparse
import os


def c_chunks(data, max_width=110):
    atoms = []
    for byte in data:
        if byte == 0x22:
            atoms.append('\\"')
        elif byte == 0x5C:
            atoms.append("\\\\")
        elif byte == 0x0A:
            atoms.append("\\n")
        elif byte == 0x0D:
            atoms.append("\\r")
        elif byte == 0x09:
            atoms.append("\\t")
        elif 0x20 <= byte <= 0x7E:
            atoms.append(chr(byte))
        else:
            atoms.append("\\%03o" % byte)
    chunks, cur = [], ""
    for atom in atoms:
        if cur and len(cur) + len(atom) > max_width:
            chunks.append(cur)
            cur = ""
        cur += atom
    chunks.append(cur)
    return chunks


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-c", required=True)
    ap.add_argument("--out-h", required=True)
    ap.add_argument("--queries", nargs="+", required=True,
                    help="scm files; basename (minus .scm) becomes the symbol suffix")
    args = ap.parse_args()

    entries = []
    for path in args.queries:
        lang = os.path.basename(path)
        if lang.endswith(".scm"):
            lang = lang[:-4]
        lang = lang.replace("-", "_")
        with open(path, "rb") as fh:
            data = fh.read()
        entries.append((lang, data))

    with open(args.out_h, "w") as h:
        h.write("/* Auto-generated by //tools:embed_queries.py -- DO NOT EDIT. */\n")
        h.write("#ifndef EDC_EMBEDDED_QUERIES_H\n#define EDC_EMBEDDED_QUERIES_H\n")
        h.write("#include <stddef.h>\n\n")
        for lang, data in entries:
            h.write("extern const char edc_query_%s[];\n" % lang)
            # A macro (not a const size_t object) so it is a compile-time
            # constant usable in static initializers in C.
            h.write("#define EDC_QUERY_%s_SIZE %d\n" % (lang.upper(), len(data)))
        h.write("\n#endif\n")

    with open(args.out_c, "w") as c:
        c.write("/* Auto-generated by //tools:embed_queries.py -- DO NOT EDIT. */\n")
        c.write('#include "edc_embedded_queries.h"\n\n')
        for lang, data in entries:
            c.write("const char edc_query_%s[] =\n" % lang)
            for chunk in c_chunks(data):
                c.write('    "%s"\n' % chunk)
            c.write("    ;\n\n")


if __name__ == "__main__":
    main()
