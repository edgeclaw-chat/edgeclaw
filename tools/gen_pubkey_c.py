#!/usr/bin/env python3
"""Turn the release signing public key (PEM) into a C array the binary can embed.

    python3 tools/gen_pubkey_c.py tools/update_signing.pub.pem > src/common/edc_update_pubkey.c

Why embed it rather than read a file at runtime: the public key is the trust anchor for
self-update. If it lived in a file next to the binary, an attacker who can replace the
binary could replace the key too, and the signature check would happily pass against
whatever they signed. Compiling it in makes "which key do I trust" a property of the build.

The format is the raw uncompressed EC point -- 0x04 || X (32 bytes) || Y (32 bytes) -- which
is what mbedtls_ecp_point_read_binary() consumes directly. Extracting it here, rather than
parsing PEM at run time, keeps the C side free of ASN.1.

Refuses to emit anything for a key that is not P-256 on the curve we verify with: a silent
mismatch here would only surface as "every update is rejected".
"""
import base64
import re
import subprocess
import sys

EXPECTED_CURVE = "prime256v1"


def der_to_raw_point(spki_der: bytes) -> bytes:
    """Pull the uncompressed point out of a SubjectPublicKeyInfo DER blob."""
    # The EC point is the last BIT STRING payload. Rather than implement ASN.1, ask openssl
    # for the public key in DER and locate the 0x03 0x42 0x00 0x04 marker: a 66-byte BIT
    # STRING holding a 65-byte uncompressed point. This shape is fixed for P-256.
    marker = b"\x03\x42\x00\x04"
    idx = spki_der.rfind(marker)
    if idx < 0:
        raise SystemExit("could not locate an uncompressed P-256 point in the key")
    point = spki_der[idx + 3: idx + 3 + 65]
    if len(point) != 65 or point[0] != 0x04:
        raise SystemExit("extracted point is not a 65-byte uncompressed EC point")
    return point


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: gen_pubkey_c.py <public-key.pem>")

    pem_path = sys.argv[1]
    with open(pem_path, "rb") as f:
        pem = f.read()
    if b"BEGIN PUBLIC KEY" not in pem:
        raise SystemExit(f"{pem_path} is not a PEM public key")

    # Confirm the curve first: a P-384 key would extract to the wrong length and every
    # verification would fail with a confusing error.
    text = subprocess.run(
        ["openssl", "pkey", "-pubin", "-in", pem_path, "-text", "-noout"],
        capture_output=True, check=True,
    ).stdout.decode("utf-8", "replace")
    if EXPECTED_CURVE not in text and "prime256v1" not in text and "P-256" not in text:
        raise SystemExit(
            f"{pem_path} is not a {EXPECTED_CURVE} key; the verifier is compiled for P-256"
        )

    der = subprocess.run(
        ["openssl", "pkey", "-pubin", "-in", pem_path, "-outform", "DER"],
        capture_output=True, check=True,
    ).stdout
    point = der_to_raw_point(der)
    assert len(point) == 65

    lines = []
    for i in range(0, len(point), 8):
        chunk = ", ".join(f"0x{b:02x}" for b in point[i: i + 8])
        lines.append(f"    {chunk},")

    key_id = subprocess.run(
        ["openssl", "pkey", "-pubin", "-in", pem_path, "-outform", "DER"],
        capture_output=True, check=True,
    ).stdout
    import hashlib
    fingerprint = hashlib.sha256(key_id).hexdigest()

    sys.stdout.write(f"""/* GENERATED by tools/gen_pubkey_c.py -- do not edit by hand.
 *
 * Source: {pem_path.split('/')[-1]}
 * Curve:  P-256 (prime256v1)
 * SHA-256 of the DER public key: {fingerprint}
 *
 * This is the trust anchor for self-update: releases are accepted only when
 * sha256sums.txt carries a signature that verifies against this point. It is compiled in
 * rather than read from a file so that replacing the binary cannot also replace the key.
 *
 * Regenerate after rotating the signing key:
 *   python3 tools/gen_pubkey_c.py tools/update_signing.pub.pem > src/common/edc_update_pubkey.c
 */
#include "edc_update_pubkey.h"

const unsigned char edc_update_pubkey_point[EDC_UPDATE_PUBKEY_LEN] = {{
{chr(10).join(lines)}
}};
""")


if __name__ == "__main__":
    main()
