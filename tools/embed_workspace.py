#!/usr/bin/env python3
"""Embed the workspace/ tree into a C translation unit.

Invoked by the genrule //src/common:workspace_embedded_c. Every file under
workspace/ becomes an entry in the `edc_bundled_workspace_entries` table
declared by src/common/edc_bundled_workspace.h, so the binary no longer needs
the source tree on disk at runtime.
"""

import argparse


def c_string_literal(data, max_width=110):
    """Return a list of C string-literal chunks representing `data`."""
    atoms = []
    for byte in data:
        if byte == 0x22:
            atoms.append('\\"')
        elif byte == 0x5C:
            atoms.append('\\\\')
        elif byte == 0x0A:
            atoms.append('\\n')
        elif byte == 0x0D:
            atoms.append('\\r')
        elif byte == 0x09:
            atoms.append('\\t')
        elif 0x20 <= byte <= 0x7E:
            atoms.append(chr(byte))
        else:
            # Always 3 octal digits, so a following digit cannot be swallowed
            # into the escape sequence.
            atoms.append('\\%03o' % byte)

    chunks = []
    current = ''
    for atom in atoms:
        if current and len(current) + len(atom) > max_width:
            chunks.append(current)
            current = ''
        current += atom
    chunks.append(current)
    return chunks


def strip_prefix(path, prefix):
    """The embedded name for |path|, with |prefix| removed.

    Separators are normalised BEFORE the comparison, and that is load-bearing rather than
    cosmetic: a genrule's `cmd_bat` on Windows hands over `docs\\edgeclaw.md`, while the POSIX
    `cmd` hands over `docs/edgeclaw.md`. Comparing the raw string let the Windows spelling pass
    through unstripped, so every entry was named `docs/...` instead of `...` and every lookup
    missed -- a bundle that was present but unreachable by name.

    |path| itself is still what gets opened; only the derived name is normalised.
    """
    name = path.replace('\\', '/')
    if not prefix:
        return name
    pre = prefix.replace('\\', '/').rstrip('/') + '/'
    if name.startswith(pre):
        return name[len(pre):]
    # A rooted spelling (an absolute execroot path) still contains the prefix as a path
    # component, so cut at it rather than embedding the whole path as the name.
    idx = name.find('/' + pre)
    if idx >= 0:
        return name[idx + len(pre) + 1:]
    return name


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, help='C source file to generate')
    parser.add_argument('--header', default='edc_bundled_workspace.h',
                        help='header that declares the table')
    parser.add_argument('--name', default='edc_bundled_workspace',
                        help='base name of the generated symbols')
    parser.add_argument('--prefix', default='',
                        help='path prefix to strip from each file')
    parser.add_argument('files', nargs='+', help='files to embed')
    args = parser.parse_args()

    entries = []
    for path in args.files:
        rel = strip_prefix(path, args.prefix)
        with open(path, 'rb') as handle:
            data = handle.read()
        entries.append((rel, data))
    entries.sort(key=lambda item: item[0])

    lines = []
    lines.append('/* Auto-generated by //tools:embed_workspace.py -- DO NOT EDIT. */')
    lines.append('#include "%s"' % args.header)
    lines.append('')
    lines.append('/* clang-format off */')

    for index, (rel, data) in enumerate(entries):
        lines.append('')
        lines.append('static const unsigned char %s_%d[] =' % (args.name, index))
        for chunk in c_string_literal(data):
            lines.append('    "%s"' % chunk)
        lines.append('    ;')

    lines.append('')
    lines.append('const struct edc_bundled_file %s_entries[] = {' % args.name)
    for index, (rel, _data) in enumerate(entries):
        lines.append('    {"%s", %s_%d, sizeof(%s_%d) - 1},' % (
            rel.replace('\\', '\\\\').replace('"', '\\"'),
            args.name, index, args.name, index))
    lines.append('};')
    lines.append('')
    lines.append('const size_t %s_count = %d;' % (args.name, len(entries)))
    lines.append('/* clang-format on */')
    lines.append('')

    with open(args.out, 'w') as handle:
        handle.write('\n'.join(lines))


if __name__ == '__main__':
    main()
