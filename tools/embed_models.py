#!/usr/bin/env python3
"""Embed the AI-model catalog (models_catalog.json) into a C byte array.

The catalog is a GENERATED build input: it is not committed (see .gitignore) and is
produced by tools/gen_models.py, which fetches models.dev and tests every provider. So
regenerate it before packaging (see tools/package.sh) and the binary ships a fresh one.

When the file is absent -- a plain `bazel build` on a clean checkout, where the sandbox
has no network -- an EMPTY catalog is embedded so the build still succeeds; the wizard
simply has no providers until the catalog is generated.
"""

import argparse

EMPTY_CATALOG = b'{"source":"empty","models":{},"providers":{}}'


def c_string_literal(data, max_width=110):
    """Return a list of C string-literal chunks representing `data`."""
    atoms = []
    for byte in data:
        if byte == 0x22:
            atoms.append('\\"')
        elif byte == 0x5C:
            atoms.append('\\\\')
        elif byte == 0x0A:
            atoms.append('\\n')
        elif byte == 0x0D:
            atoms.append('\\r')
        elif byte == 0x09:
            atoms.append('\\t')
        elif 0x20 <= byte <= 0x7E:
            atoms.append(chr(byte))
        else:
            # Always 3 octal digits, so a following digit cannot be swallowed
            # into the escape sequence.
            atoms.append('\\%03o' % byte)

    chunks = []
    current = ''
    for atom in atoms:
        if current and len(current) + len(atom) > max_width:
            chunks.append(current)
            current = ''
        current += atom
    chunks.append(current)
    return chunks


def emit_c(out_path, header, name, data):
    """Write a C translation unit defining `name` (bytes) and `name`_size."""
    lines = []
    lines.append('/* Auto-generated by //tools:embed_models.py -- DO NOT EDIT. */')
    lines.append('#include "%s"' % header)
    lines.append('')
    lines.append('/* clang-format off */')
    lines.append('const unsigned char %s[] =' % name)
    for chunk in c_string_literal(data):
        lines.append('    "%s"' % chunk)
    lines.append('    ;')
    lines.append('const size_t %s_size = %d;' % (name, len(data)))
    lines.append('/* clang-format on */')
    lines.append('')
    with open(out_path, 'w') as handle:
        handle.write('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, help='C source file to generate')
    parser.add_argument('--name', required=True, help='symbol base name')
    parser.add_argument('--header', required=True, help='header declaring the symbols')
    parser.add_argument('input', nargs='?', help='models_catalog.json (omitted => empty catalog)')
    args = parser.parse_args()

    data = EMPTY_CATALOG
    if args.input:
        with open(args.input, 'rb') as handle:
            data = handle.read() or EMPTY_CATALOG

    emit_c(args.out, args.header, args.name, data)


if __name__ == '__main__':
    main()
