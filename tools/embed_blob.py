#!/usr/bin/env python3
"""Embed a single file as a C byte array.

Build-time helper (see the genrule //src/agent:sandbox_helper_embedded_c): it
turns the sandbox helper executable into a byte array so it can be linked into
the main binary and the release stays a single self-contained file.
"""

import argparse


def c_string_literal(data, max_width=110):
    """Return a list of C string-literal chunks representing `data`."""
    atoms = []
    for byte in data:
        if byte == 0x22:
            atoms.append('\\"')
        elif byte == 0x5C:
            atoms.append('\\\\')
        elif byte == 0x0A:
            atoms.append('\\n')
        elif byte == 0x0D:
            atoms.append('\\r')
        elif byte == 0x09:
            atoms.append('\\t')
        elif 0x20 <= byte <= 0x7E:
            atoms.append(chr(byte))
        else:
            # Always 3 octal digits, so a following digit cannot be swallowed
            # into the escape sequence.
            atoms.append('\\%03o' % byte)

    chunks = []
    current = ''
    for atom in atoms:
        if current and len(current) + len(atom) > max_width:
            chunks.append(current)
            current = ''
        current += atom
    chunks.append(current)
    return chunks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--in', dest='inp', required=True, help='file to embed')
    parser.add_argument('--out', required=True, help='C source file to generate')
    parser.add_argument('--name', required=True, help='symbol base name')
    parser.add_argument('--header', required=True, help='header declaring the symbols')
    args = parser.parse_args()

    with open(args.inp, 'rb') as handle:
        data = handle.read()

    lines = []
    lines.append('/* Auto-generated by //tools:embed_blob.py -- DO NOT EDIT. */')
    lines.append('#include "%s"' % args.header)
    lines.append('')
    lines.append('/* clang-format off */')
    lines.append('const unsigned char %s[] =' % args.name)
    for chunk in c_string_literal(data):
        lines.append('    "%s"' % chunk)
    lines.append('    ;')
    lines.append('const size_t %s_size = %d;' % (args.name, len(data)))
    lines.append('/* clang-format on */')
    lines.append('')

    with open(args.out, 'w') as handle:
        handle.write('\n'.join(lines))


if __name__ == '__main__':
    main()
