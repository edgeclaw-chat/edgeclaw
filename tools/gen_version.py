#!/usr/bin/env python3
"""Generate the version header from git, at build time.

WHY A GENERATED HEADER RATHER THAN A CHECKED-IN NUMBER: a hand-maintained version string
drifts from the commit it claims to describe, and the drift is invisible until a user
reports a bug against a version that was never released. Deriving it makes that
impossible.

WHY A local=1 GENRULE RATHER THAN --workspace_status_command: the status-command route
needs Bazel's stamp/status plumbing, and the genrule that consumes it has to be written
twice (cmd for Windows, sh everywhere else) with different quoting. This project already
builds generated C through Python genrules (embed_workspace.py, embed_models.py), so the
same shape is used here: one script, one code path, every platform. `local = 1` is what
lets it read .git, which a sandboxed action does not get.

The output changes only when the commit or the dirty state changes, so Bazel's action
cache still works: the rule runs on every build (it is cheap), but downstream compiles
only when the generated bytes differ.
"""

import argparse
import os
import subprocess
import sys

TEMPLATE = """\
/* GENERATED BY tools/gen_version.py -- DO NOT EDIT.
 *
 * Source of truth: `git describe` at build time. See that script for why this is generated
 * rather than written down.
 */
#ifndef EDC_VERSION_GEN_H
#define EDC_VERSION_GEN_H

#define EDC_VERSION "{version}"
#define EDC_COMMIT "{commit}"
#define EDC_BUILD_TIME "{build_time}"

#endif /* EDC_VERSION_GEN_H */
"""


def git(root, *args):
    """Run a git command, returning "" on any failure.

    Failure is normal, not exceptional: a source tarball has no .git, and a build must
    still produce a working binary (it just says "unknown"). Never raise from here.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", root] + list(args),
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=15,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    if proc.returncode != 0:
        return ""
    return proc.stdout.decode("utf-8", "replace").strip()


def c_escape(s):
    """Make a string safe to place inside a C string literal."""
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\r", ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, help="header to write")
    ap.add_argument("--repo", required=True,
                    help="any tracked file; its REAL path locates the checkout")
    args = ap.parse_args()

    # --repo arrives as an execroot path, and the execroot is NOT the checkout: its files are
    # symlinks to the checkout and it carries a symlink to the checkout's .git. Running git
    # there makes every file look typechanged (a symlink where the index expects a regular
    # file), so `git describe --dirty` reports "-dirty" for a perfectly clean tree -- which is
    # exactly what happened: a binary announced "-dirty" while `git status` in the checkout
    # said clean. Resolving through the .git symlink lands on the checkout, and does the same
    # thing when the path already IS the checkout (.git there is a real directory).
    root = os.path.dirname(os.path.realpath(args.repo))
    # (named gitdir, not `git`: `git` is the helper function below, and shadowing it with a
    # path string turns every later call into "str object is not callable")
    gitdir = os.path.join(root, ".git")
    if os.path.exists(gitdir):
        candidate = os.path.dirname(os.path.realpath(gitdir))
        if os.path.isdir(candidate):
            root = candidate

    version = git(root, "describe", "--tags", "--always", "--dirty") or "unknown"
    commit = git(root, "rev-parse", "--short", "HEAD") or "unknown"
    # The commit date, not "now": a rebuild of the same commit should produce the same
    # bytes, or every build would invalidate the cache for no information gained.
    build_time = git(root, "log", "-1", "--format=%cI") or "unknown"

    body = TEMPLATE.format(version=c_escape(version),
                           commit=c_escape(commit),
                           build_time=c_escape(build_time))

    # Only rewrite when the content changes, so the file's mtime (and therefore the
    # compile that depends on it) is stable across no-op builds.
    try:
        with open(args.out, "r", encoding="utf-8") as f:
            if f.read() == body:
                return 0
    except OSError:
        pass

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
